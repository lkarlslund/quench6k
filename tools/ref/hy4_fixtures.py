#!/usr/bin/env python3
"""Hy4-flash versions of the oracle fixtures: each Qwen fixture's conversation re-rendered with Hy4-flash's
chat template, followed by its completion text, tokenized with Hy4-flash's tokenizer.

The completions were generated by another model, so they serve as teacher-forced text.

    python3 -I tools/ref/hy4_fixtures.py --model <hy4 checkpoint> --qwen <qwen checkpoint> --out out/hy4-fixtures
"""
import argparse
import json
import pathlib
import re

import jinja2
from tokenizers import Tokenizer

TURN = re.compile(r"<\|im_start\|>(\w+)\n(.*?)<\|im_end\|>\n?", re.S)


def render(template, messages, thinking):
    env = jinja2.Environment(extensions=["jinja2.ext.loopcontrols"])

    def tojson(v, ensure_ascii=True, **kw):
        return json.dumps(v, ensure_ascii=ensure_ascii, **kw)

    def raise_exception(msg):
        raise RuntimeError(msg)

    env.filters["tojson"] = tojson
    env.globals["raise_exception"] = raise_exception
    return env.from_string(template).render(
        messages=messages, add_generation_prompt=True, reasoning_effort="high" if thinking else "no_think")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", required=True)
    ap.add_argument("--qwen", required=True, help="checkpoint with the Qwen tokenizer.json of the fixtures")
    ap.add_argument("--fixtures", default="oracle/fixtures")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    model = pathlib.Path(args.model)
    hy = Tokenizer.from_file(str(model / "tokenizer.json"))
    qwen = Tokenizer.from_file(str(pathlib.Path(args.qwen) / "tokenizer.json"))
    template = (model / "chat_template.jinja").read_text()
    for d in sorted(pathlib.Path(args.fixtures).iterdir()):
        if not (d / "spec.json").exists():
            continue
        spec = json.loads((d / "spec.json").read_text())
        seq = json.loads((d / "sequence.json").read_text())
        thinking = bool(spec.get("enable_thinking"))
        messages = []
        for role, body in TURN.findall(spec["text"]):
            if role == "assistant":
                body = re.sub(r"^<think>.*?</think>\s*", "", body, flags=re.S)
            messages.append({"role": role, "content": body})
        prompt = render(template, messages, thinking)
        completion = qwen.decode(seq["tokens"][seq["prompt_len"]:], skip_special_tokens=False)
        completion = completion.replace("<|im_end|>", "<｜hy_end:opensource｜>")
        if thinking:
            completion = re.sub(r"^\s*<think>\s*", "", completion)
            completion = completion.replace("</think>", "</think:opensource>")
        else:
            completion = re.sub(r"^\s*<think>\s*</think>\s*", "", completion)
        p_ids = hy.encode(prompt, add_special_tokens=False).ids
        c_ids = hy.encode(completion, add_special_tokens=False).ids
        out = pathlib.Path(args.out) / d.name
        out.mkdir(parents=True, exist_ok=True)
        (out / "sequence.json").write_text(json.dumps({
            "generator": f"text of oracle/fixtures/{d.name}, Hy4-flash template and tokenizer",
            "prompt_len": len(p_ids), "tokens": p_ids + c_ids}) + "\n")
        print(f"{d.name:14s} prompt {len(p_ids):6d} completion {len(c_ids):5d}")


if __name__ == "__main__":
    main()
