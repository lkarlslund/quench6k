#!/usr/bin/env python3
"""Inkling 2 Mini versions of the oracle fixtures: each Qwen fixture's conversation and completion
re-rendered with Inkling's chat template (the completion as the assistant turn: its thinking as
reasoning_content, the rest as content) and tokenized with Inkling's tokenizer.

The completions were generated by another model, so they serve as teacher-forced text.

    python3 -I tools/ref/inkling_fixtures.py --model <inkling checkpoint> --qwen <qwen checkpoint> --out out/inkling-fixtures
"""
import argparse
import json
import pathlib
import re

import jinja2
from jinja2 import nodes
from jinja2.ext import Extension
from tokenizers import Tokenizer

TURN = re.compile(r"<\|im_start\|>(\w+)\n(.*?)<\|im_end\|>\n?", re.S)


class Generation(Extension):
    """{% generation %} ... {% endgeneration %} of transformers chat templates: renders its body."""
    tags = {"generation"}

    def parse(self, parser):
        lineno = next(parser.stream).lineno
        body = parser.parse_statements(("name:endgeneration",), drop_needle=True)
        return nodes.CallBlock(self.call_method("_render"), [], [], body).set_lineno(lineno)

    def _render(self, caller):
        return caller()


def render(template, messages, effort):
    env = jinja2.Environment(extensions=["jinja2.ext.loopcontrols", Generation])

    def tojson(v, ensure_ascii=False, sort_keys=False, separators=None, **kw):
        return json.dumps(v, ensure_ascii=ensure_ascii, sort_keys=sort_keys, separators=separators, **kw)

    def raise_exception(msg):
        raise RuntimeError(msg)

    env.filters["tojson"] = tojson
    env.globals["raise_exception"] = raise_exception
    return env.from_string(template).render(messages=messages, reasoning_effort=effort)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", required=True)
    ap.add_argument("--qwen", required=True, help="checkpoint with the Qwen tokenizer.json of the fixtures")
    ap.add_argument("--fixtures", default="oracle/fixtures")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    model = pathlib.Path(args.model)
    tok = Tokenizer.from_file(str(model / "tokenizer.json"))
    qwen = Tokenizer.from_file(str(pathlib.Path(args.qwen) / "tokenizer.json"))
    template = (model / "chat_template.jinja").read_text()
    for d in sorted(pathlib.Path(args.fixtures).iterdir()):
        if not (d / "spec.json").exists():
            continue
        spec = json.loads((d / "spec.json").read_text())
        seq = json.loads((d / "sequence.json").read_text())
        effort = "high" if spec.get("enable_thinking") else "none"
        messages = []
        for role, body in TURN.findall(spec["text"]):
            if role == "assistant":
                body = re.sub(r"^<think>.*?</think>\s*", "", body, flags=re.S)
            messages.append({"role": role, "content": body})
        completion = qwen.decode(seq["tokens"][seq["prompt_len"]:], skip_special_tokens=False)
        completion = completion.replace("<|im_end|>", "").replace("<|endoftext|>", "")
        # Thinking fixtures' completions start inside the thinking (the Qwen prompt opens it); a completion
        # cut off before </think> is all thinking.
        completion = re.sub(r"^\s*<think>", "", completion)
        thinking, _, answer = completion.partition("</think>") if "</think>" in completion or effort != "none" else ("", "", completion)
        reply = {"role": "assistant", "content": answer.strip()}
        if thinking.strip():
            reply["reasoning_content"] = thinking.strip()
        prompt = render(template, messages, effort)
        full = render(template, messages + [reply], effort)
        p_ids = tok.encode(prompt, add_special_tokens=False).ids
        ids = tok.encode(full, add_special_tokens=False).ids
        if ids[:len(p_ids)] != p_ids:
            raise SystemExit(f"{d.name}: the conversation's tokens do not start with the prompt's")
        out = pathlib.Path(args.out) / d.name
        out.mkdir(parents=True, exist_ok=True)
        (out / "sequence.json").write_text(json.dumps({
            "generator": f"text of oracle/fixtures/{d.name}, Inkling 2 template and tokenizer",
            "prompt_len": len(p_ids), "tokens": ids}) + "\n")
        print(f"{d.name:14s} prompt {len(p_ids):6d} completion {len(ids) - len(p_ids):5d}")


if __name__ == "__main__":
    main()
